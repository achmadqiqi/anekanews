## Persyaratan Umum dan Kriteria Kelayakan Debitur KUR 2026

Untuk memastikan alokasi dana subsidi KUR tepat sasaran, pemerintah menetapkan kriteria kelayakan calon debitur yang wajib dipenuhi:

- **Usia Usaha Aktif:** Memiliki usaha produktif yang telah berjalan secara aktif minimal selama 6 bulan berturut-turut.
- **Legalitas Identitas:** Memiliki Kartu Tanda Penduduk (KTP) elektronik, Kartu Keluarga (KK), dan Surat Izin Usaha (minimal Surat Keterangan Usaha dari Desa/Kelurahan atau NIB).
- **Bebas Kredit Komersial:** Debitur sedang tidak menerima kredit pembiayaan modal kerja atau investasi komersial dari perbankan lain (kecuali kredit konsumtif seperti KPR, KBR, atau kartu kredit dengan kolektibilitas lancar).
- **Riwayat SLIK OJK Bersih:** Memiliki catatan riwayat pinjaman lancar pada Sistem Layanan Informasi Keuangan (SLIK) OJK.

