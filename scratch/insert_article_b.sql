## Kebijakan Suku Bunga Subsidi dan Skema Penyaluran KUR 2026

Dalam upaya menjaga keterjangkauan pembayaran angsuran bagi pelaku usaha mikro, pemerintah tetap mempertahankan subsidi bunga pinjaman yang sangat signifikan. Suku bunga KUR untuk debitur baru penerima KUR Mikro ditetapkan sebesar **6% efektif per tahun**.

