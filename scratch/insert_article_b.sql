## Pengelompokan Jenis KUR dan Batas Maksimal Pinjaman

Program Kredit Usaha Rakyat 2026 dibagi ke dalam beberapa kategori utama yang disesuaikan dengan skala dan kebutuhan operasional UMKM:

1. **KUR Super Mikro:** Plafon pinjaman hingga Rp10 juta dengan suku bunga subsidi super murah 3% efektif per tahun. Ditujukan khusus bagi pekerja terkena PHK, ibu rumah tangga pemilik usaha mikro, atau pemula bisnis.
2. **KUR Mikro:** Plafon pinjaman mulai dari di atas Rp10 juta hingga maksimal Rp100 juta per debitur tanpa jaminan agunan fisik tambahan.
3. **KUR Kecil:** Plafon pinjaman mulai dari di atas Rp100 juta hingga maksimal Rp500 juta. Kategori ini memerlukan agunan tambahan sesuai dengan kebijakan internal bank penyalur.
