## Pengertian Agentic AI dan Perbedaannya dengan Generative AI Biasa

Untuk memahami potensi penuh dari teknologi ini, penting untuk membedakan antara kecerdasan buatan generatif (*Generative AI*) biasa dengan sistem berbasis *Agentic AI*. Generative AI bertindak seperti asisten terpasang yang menunggu instruksi eksplisit pengguna untuk membuat teks, gambar, atau merangkum dokumen.

Sebaliknya, *Agentic AI* beroperasi layaknya seorang karyawan virtual otonom yang diberikan sasaran akhir (*goal-oriented*). Agen AI mampu memecah sasaran besar menjadi langkah-langkah kerja kecil, memilih perangkat lunak yang tepat untuk menyelesaikan tugas, mengeksekusi tindakan, serta mengevaluasi hasil kerjanya sendiri.

Sebagai contoh, jika Anda meminta agen AI untuk ''menyusun laporan analisis pesaing bisnis minggu ini'', agen akan secara otomatis mencari informasi terbaru di web, mengumpulkan data harga produk lawan, menyusun grafik komparasi, dan mengirimkan draf laporan akhir ke email Anda tanpa perlu diarahkan langkah demi langkah.

